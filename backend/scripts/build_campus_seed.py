FLOOR_LABEL = {"G": "G층", "L": "L층"}


def main() -> None:
    buildings = [
        {
            "id": f"bld_{code}",
            "code": code,
            "name": f"{code} {name}" if code[0] in "ERS" and code[1:].isdigit() else name,
            "aliases": sorted({code, name, f"{code}동", *aliases}),
            "lat": lat,
            "lng": lng,
        }
        for code, name, aliases, lat, lng in BUILDINGS
    ]

    plans, rooms = [], []
    seen_rooms: set[str] = set()
    plan_count: dict[str, int] = {}
    for bld, floor, img, w, h, plan_rooms in PLANS:
        key = f"{bld}_{floor}"
        plan_count[key] = plan_count.get(key, 0) + 1
        plan_id = f"plan_{key}_{plan_count[key]}"
        plans.append(
            {
                "id": plan_id,
                "building_id": f"bld_{bld}",
                "floor": floor,
                "floor_label": FLOOR_LABEL.get(floor, f"{floor}층"),
                "image_url": IMG_BASE + img,
                "width": w,
                "height": h,
                "source_url": PLAN_SOURCE,
            }
        )
        for code, name, x, y in plan_rooms:
            room_id = f"room_{bld}_{code}"
            if room_id in seen_rooms:  # 같은 번호가 두 번(예: E6 208) 나오면 이름으로 구분
                room_id = f"{room_id}_{len([r for r in rooms if r['id'].startswith(room_id)]) + 1}"
            seen_rooms.add(room_id)
            rooms.append(
                {
                    "id": room_id,
                    "building_id": f"bld_{bld}",
                    "code": code,
                    "name": name or None,
                    "floor": floor,
                    "plan_id": plan_id,
                    "x": x,
                    "y": y,
                }
            )

    SEED.mkdir(parents=True, exist_ok=True)
    for name, data in (("buildings", buildings), ("floor_plans", plans), ("rooms", rooms)):
        (SEED / f"{name}.json").write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"buildings {len(buildings)}, floor_plans {len(plans)}, rooms {len(rooms)}")


